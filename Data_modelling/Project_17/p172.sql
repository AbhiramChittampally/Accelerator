CREATE OR REPLACE SECURE VIEW COMPLIANCE_BANK_TRANSACTIONS AS
SELECT
    TXN_ID,
    CLIENT_ID,
    CLIENT_SSN,
    REGION,
    ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE
FROM SILVER_BANK_TRANSACTIONS
WHERE CURRENT_ROLE() = 'COMPLIANCE_OFFICER';

CREATE OR REPLACE SECURE VIEW NA_BANK_TRANSACTIONS AS
SELECT
    TXN_ID,
    CLIENT_ID,
    CASE
        WHEN CURRENT_ROLE() = 'NA_ANALYST'
        THEN '***-**-' || RIGHT(CLIENT_SSN, 4)
        ELSE NULL
    END AS CLIENT_SSN,
    REGION,
    CASE
        WHEN CURRENT_ROLE() = 'NA_ANALYST'
        THEN 'ACT-****'
        ELSE NULL
    END AS ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE
FROM SILVER_BANK_TRANSACTIONS
WHERE CURRENT_ROLE() = 'NA_ANALYST'
AND REGION = 'NA';

CREATE OR REPLACE SECURE VIEW EU_BANK_TRANSACTIONS AS
SELECT
    TXN_ID,
    CLIENT_ID,
    CASE
        WHEN CURRENT_ROLE() = 'EU_ANALYST'
        THEN '***-**-' || RIGHT(CLIENT_SSN, 4)
        ELSE NULL
    END AS CLIENT_SSN,
    REGION,
    CASE
        WHEN CURRENT_ROLE() = 'EU_ANALYST'
        THEN 'ACT-****'
        ELSE NULL
    END AS ACCOUNT_NO,
    AMOUNT,
    STATUS,
    AML_RISK_SCORE
FROM SILVER_BANK_TRANSACTIONS
WHERE CURRENT_ROLE() = 'EU_ANALYST'
AND REGION = 'EU';

