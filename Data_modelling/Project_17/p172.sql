CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY AS
SELECT
    REGION,
    SUM(AMOUNT) AS TOTAL_SETTLED_VAL,
    COUNT(*) AS SETTLED_TXN_COUNT,
    ROUND(AVG(AMOUNT), 2) AS AVG_SETTLED_AMOUNT
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION;

SELECT
    REGION,
    TOTAL_SETTLED_VAL,
    SETTLED_TXN_COUNT,
    AVG_SETTLED_AMOUNT
FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
ORDER BY REGION;

SELECT
    SUM(AMOUNT) AS BRONZE_GROSS_TOTAL
FROM SILVER_BANK_TRANSACTIONS;

SELECT
    SUM(AMOUNT) AS SILVER_GROSS_TOTAL
FROM SILVER_BANK_TRANSACTIONS;

SELECT
    SUM(TOTAL_SETTLED_VAL) AS GOLD_GROSS_TOTAL
FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY;

SELECT
    b.BRONZE_GROSS_TOTAL,
    s.SILVER_GROSS_TOTAL,
    g.GOLD_GROSS_TOTAL,
    CASE
        WHEN b.BRONZE_GROSS_TOTAL = s.SILVER_GROSS_TOTAL
        THEN TRUE
        ELSE FALSE
    END AS RECONCILED_FLAG
FROM
(
    SELECT SUM(AMOUNT) AS BRONZE_GROSS_TOTAL
    FROM SILVER_BANK_TRANSACTIONS
) b
CROSS JOIN
(
    SELECT SUM(AMOUNT) AS SILVER_GROSS_TOTAL
    FROM SILVER_BANK_TRANSACTIONS
) s
CROSS JOIN
(
    SELECT SUM(TOTAL_SETTLED_VAL) AS GOLD_GROSS_TOTAL
    FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
) g;

