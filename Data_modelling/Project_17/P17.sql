CREATE DATABASE IF NOT EXISTS P17_FINANCIAL_GOVERNANCE_DB;

CREATE SCHEMA IF NOT EXISTS P17_FINANCIAL_GOVERNANCE_DB.P17_WEALTH_CORE;

USE DATABASE P17_FINANCIAL_GOVERNANCE_DB;

USE SCHEMA P17_WEALTH_CORE;

CREATE WAREHOUSE IF NOT EXISTS P17_COMPUTE_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE FILE FORMAT IF NOT EXISTS P17_JSON_FORMAT
TYPE = JSON
STRIP_OUTER_ARRAY = FALSE;

CREATE FILE FORMAT IF NOT EXISTS P17_TEXT_FORMAT
TYPE = CSV
FIELD_DELIMITER = NONE
RECORD_DELIMITER = '\n';

CREATE STAGE IF NOT EXISTS P17_WEALTH_STAGE
FILE_FORMAT = P17_JSON_FORMAT;

CREATE OR REPLACE TABLE BRONZE_BANK_PAYLOADS (
    INGEST_ID INTEGER AUTOINCREMENT,
    PAYLOAD VARIANT,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE QUARANTINE_GOVERNANCE_PAYLOADS (
    QUARANTINE_ID INTEGER AUTOINCREMENT,
    RAW_RECORD_TEXT STRING,
    REASON STRING
);

LIST @P17_WEALTH_STAGE;

COPY INTO BRONZE_BANK_PAYLOADS (PAYLOAD)
FROM @P17_WEALTH_STAGE
FILE_FORMAT = P17_JSON_FORMAT
ON_ERROR = 'CONTINUE';

SELECT COUNT(*) AS TOTAL_BRONZE_RECORDS
FROM BRONZE_BANK_PAYLOADS;

INSERT INTO QUARANTINE_GOVERNANCE_PAYLOADS (
    RAW_RECORD_TEXT,
    REASON
)
SELECT
    $1::STRING,
    'MALFORMED_JSON_BODY'
FROM @P17_WEALTH_STAGE
(
    FILE_FORMAT => P17_TEXT_FORMAT
)
WHERE TRY_PARSE_JSON($1::STRING) IS NULL;

SELECT
    QUARANTINE_ID,
    RAW_RECORD_TEXT,
    REASON
FROM QUARANTINE_GOVERNANCE_PAYLOADS
ORDER BY QUARANTINE_ID;

