CREATE OR REPLACE MASKING POLICY MASK_SSN
AS (VAL STRING)
RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() = 'P17_COMPLIANCE_OFFICER'
            THEN VAL
        ELSE '***-**-' || RIGHT(VAL, 4)
    END;

CREATE OR REPLACE MASKING POLICY MASK_ACCOUNT
AS (VAL STRING)
RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() = 'P17_COMPLIANCE_OFFICER'
            THEN VAL
        ELSE 'ACT-****'
    END;

ALTER TABLE SILVER_BANK_TRANSACTIONS
MODIFY COLUMN CLIENT_SSN
SET MASKING POLICY MASK_SSN;

ALTER TABLE SILVER_BANK_TRANSACTIONS
MODIFY COLUMN ACCOUNT_NO
SET MASKING POLICY MASK_ACCOUNT;

CREATE OR REPLACE ROW ACCESS POLICY RAP_REGION_POLICY
AS (REGION_VALUE STRING)
RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() = 'P17_COMPLIANCE_OFFICER'
            THEN TRUE
        WHEN CURRENT_ROLE() = 'P17_NA_ANALYST'
            THEN REGION_VALUE = 'NA'
        WHEN CURRENT_ROLE() = 'P17_EU_ANALYST'
            THEN REGION_VALUE = 'EU'
        ELSE FALSE
    END;

ALTER TABLE SILVER_BANK_TRANSACTIONS
ADD ROW ACCESS POLICY RAP_REGION_POLICY
ON (REGION);

CREATE OR REPLACE SECURE VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY AS
SELECT
    REGION,
    SUM(AMOUNT) AS TOTAL_SETTLED_VAL,
    COUNT(*) AS SETTLED_TXN_COUNT,
    AVG(AMOUNT) AS AVG_SETTLED_AMOUNT
FROM SILVER_BANK_TRANSACTIONS
WHERE STATUS = 'SETTLED'
GROUP BY REGION;

GRANT SELECT ON VIEW SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
TO ROLE P17_COMPLIANCE_OFFICER;

SELECT
    REGION,
    TOTAL_SETTLED_VAL,
    SETTLED_TXN_COUNT,
    ROUND(AVG_SETTLED_AMOUNT, 2) AS AVG_SETTLED_AMOUNT
FROM SECURE_GOLD_EXTERNAL_AUDIT_SUMMARY
ORDER BY REGION;

SELECT
    SUM(PAYLOAD:amount::NUMBER(18,2)) AS BRONZE_GROSS_TOTAL,
    (
        SELECT SUM(AMOUNT)
        FROM SILVER_BANK_TRANSACTIONS
    ) AS SILVER_GROSS_TOTAL,
    (
        SELECT SUM(AMOUNT)
        FROM SILVER_BANK_TRANSACTIONS
        WHERE STATUS = 'SETTLED'
    ) AS GOLD_GROSS_TOTAL,
    CASE
        WHEN
            SUM(PAYLOAD:amount::NUMBER(18,2)) =
            (
                SELECT SUM(AMOUNT)
                FROM SILVER_BANK_TRANSACTIONS
            )
            AND
            (
                SELECT SUM(AMOUNT)
                FROM SILVER_BANK_TRANSACTIONS
                WHERE STATUS = 'SETTLED'
            ) = 1765000.00
        THEN TRUE
        ELSE FALSE
    END AS RECONCILED_FLAG
FROM BRONZE_BANK_PAYLOADS;