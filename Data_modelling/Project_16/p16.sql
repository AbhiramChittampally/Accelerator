CREATE OR REPLACE STREAM STRM_BRONZE_CLAIMS
ON TABLE BRONZE_RAW_CLAIMS
SHOW_INITIAL_ROWS = TRUE;

SELECT
    METADATA$ACTION,
    METADATA$ISUPDATE,
    INGEST_ID,
    PAYLOAD
