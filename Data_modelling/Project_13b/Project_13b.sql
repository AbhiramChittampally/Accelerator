-- Task 1: Create warehouse

CREATE WAREHOUSE IF NOT EXISTS RETAIL13B_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

-- Create database

CREATE DATABASE IF NOT EXISTS RETAIL13B_DW;

-- Create schema

CREATE SCHEMA IF NOT EXISTS RETAIL13B_DW.SCHEMA13B_COMPARE;

-- Set context

USE WAREHOUSE RETAIL13B_WH;
USE DATABASE RETAIL13B_DW;
USE SCHEMA SCHEMA13B_COMPARE;

SELECT
    CURRENT_WAREHOUSE(),
    CURRENT_DATABASE(),
    CURRENT_SCHEMA();


-- Create file format

CREATE FILE FORMAT IF NOT EXISTS RETAIL13B_CSV_FORMAT
TYPE = 'CSV'
SKIP_HEADER = 1
FIELD_DELIMITER = ','
FIELD_OPTIONALLY_ENCLOSED_BY = '"';


-- Create stage

CREATE STAGE IF NOT EXISTS RETAIL13B_STAGE
FILE_FORMAT = RETAIL13B_CSV_FORMAT;


-- Create source tables

CREATE OR REPLACE TABLE RETAIL13B_RAW_HOSPITAL_HIERARCHY (
    HOSPITAL_ID NUMBER,
    HOSPITAL_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    NETWORK_ID NUMBER,
    NETWORK_NAME VARCHAR(100),
    NETWORK_DIRECTOR VARCHAR(100)
);

CREATE OR REPLACE TABLE RETAIL13B_RAW_TREATMENT_HIERARCHY (
    TREATMENT_ID NUMBER,
    TREATMENT_NAME VARCHAR(100),
    DIAGNOSIS_GROUP_ID VARCHAR(30),
    DIAGNOSIS_GROUP_NAME VARCHAR(50),
    STANDARD_COST NUMBER(12,2)
);

CREATE OR REPLACE TABLE RETAIL13B_RAW_PATIENTS (
    PATIENT_ID NUMBER,
    PATIENT_NAME VARCHAR(100),
    GENDER VARCHAR(20),
    AGE NUMBER,
    CITY VARCHAR(50)
);

CREATE OR REPLACE TABLE RETAIL13B_RAW_INSURANCE_CLAIMS (
    CLAIM_ID VARCHAR(50),
    CLAIM_DATE DATE,
    PATIENT_ID NUMBER,
    HOSPITAL_ID NUMBER,
    TREATMENT_ID NUMBER,
    CLAIMED_AMOUNT NUMBER(12,2),
    APPROVED_AMOUNT NUMBER(12,2)
);


