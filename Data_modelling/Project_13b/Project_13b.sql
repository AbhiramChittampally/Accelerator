CREATE OR REPLACE TABLE SNOW_DIM_DIAGNOSIS_GROUP (
    DIAGNOSIS_GROUP_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    DIAGNOSIS_GROUP_ID VARCHAR(30),
    DIAGNOSIS_GROUP_NAME VARCHAR(50)
);


-- Create treatment dimension

CREATE OR REPLACE TABLE SNOW_DIM_TREATMENT (
    TREATMENT_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    TREATMENT_ID NUMBER,
    TREATMENT_NAME VARCHAR(100),
    STANDARD_COST NUMBER(12,2),
    DIAGNOSIS_GROUP_KEY NUMBER,
    FOREIGN KEY (DIAGNOSIS_GROUP_KEY)
        REFERENCES SNOW_DIM_DIAGNOSIS_GROUP(DIAGNOSIS_GROUP_KEY)
);


-- Task 8: Load Snowflake network dimension

INSERT INTO SNOW_DIM_NETWORK (
    NETWORK_ID,
    NETWORK_NAME,
    NETWORK_DIRECTOR
)
SELECT
    NETWORK_ID,
    NETWORK_NAME,
    NETWORK_DIRECTOR
FROM RETAIL13B_RAW_HOSPITAL_HIERARCHY
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY NETWORK_ID
    ORDER BY HOSPITAL_ID
) = 1;


-- Load Snowflake hospital dimension

INSERT INTO SNOW_DIM_HOSPITAL (
    HOSPITAL_ID,
    HOSPITAL_NAME,
    CITY,
    STATE,
    NETWORK_KEY
)
SELECT
    H.HOSPITAL_ID,
    H.HOSPITAL_NAME,
    H.CITY,
    H.STATE,
    N.NETWORK_KEY
FROM RETAIL13B_RAW_HOSPITAL_HIERARCHY H
JOIN SNOW_DIM_NETWORK N
    ON H.NETWORK_ID = N.NETWORK_ID;


-- Load Snowflake diagnosis groups

INSERT INTO SNOW_DIM_DIAGNOSIS_GROUP (
    DIAGNOSIS_GROUP_ID,
    DIAGNOSIS_GROUP_NAME
)
SELECT
    DIAGNOSIS_GROUP_ID,
    DIAGNOSIS_GROUP_NAME
FROM RETAIL13B_RAW_TREATMENT_HIERARCHY
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY DIAGNOSIS_GROUP_ID
    ORDER BY TREATMENT_ID
) = 1;


-- Load Snowflake treatments

INSERT INTO SNOW_DIM_TREATMENT (
    TREATMENT_ID,
    TREATMENT_NAME,
    STANDARD_COST,
    DIAGNOSIS_GROUP_KEY
)
SELECT
    T.TREATMENT_ID,
    T.TREATMENT_NAME,
    T.STANDARD_COST,
    D.DIAGNOSIS_GROUP_KEY
FROM RETAIL13B_RAW_TREATMENT_HIERARCHY T
JOIN SNOW_DIM_DIAGNOSIS_GROUP D
    ON T.DIAGNOSIS_GROUP_ID = D.DIAGNOSIS_GROUP_ID;


