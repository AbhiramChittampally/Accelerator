-- Create admission fact
CREATE OR REPLACE TABLE FACT_ADMISSION (
    ADMISSION_KEY INTEGER AUTOINCREMENT PRIMARY KEY,
    PATIENT_KEY INTEGER,
    DOCTOR_KEY INTEGER,
    HOSPITAL_KEY INTEGER,
    DEPARTMENT_KEY INTEGER,
    DATE_KEY INTEGER,
    ADMISSION_COUNT INTEGER,
    LENGTH_OF_STAY INTEGER
);

-- Load admission fact
INSERT INTO FACT_ADMISSION (
    PATIENT_KEY,
    DOCTOR_KEY,
    HOSPITAL_KEY,
    DEPARTMENT_KEY,
    DATE_KEY,
    ADMISSION_COUNT,
    LENGTH_OF_STAY
)
SELECT
    P.PATIENT_KEY,
    D.DOCTOR_KEY,
    H.HOSPITAL_KEY,
    DP.DEPARTMENT_KEY,
    DD.DATE_KEY,
    1,
    DATEDIFF(DAY, A.ADMISSION_DATE, A.DISCHARGE_DATE)
FROM RAW_ADMISSIONS A
JOIN DIM_PATIENT P
    ON A.PATIENT_ID = P.PATIENT_ID
JOIN DIM_DOCTOR D
    ON A.DOCTOR_ID = D.DOCTOR_ID
JOIN DIM_HOSPITAL H
    ON A.HOSPITAL_ID = H.HOSPITAL_ID
JOIN DIM_DEPARTMENT DP
    ON A.DEPARTMENT_ID = DP.DEPARTMENT_ID
JOIN DIM_DATE DD
    ON A.ADMISSION_DATE = DD.FULL_DATE;

