    DATE_VALUE,
    DAY(DATE_VALUE),
    DAYNAME(DATE_VALUE),
    WEEKOFYEAR(DATE_VALUE),
    MONTH(DATE_VALUE),
    MONTHNAME(DATE_VALUE),
    'Q' || QUARTER(DATE_VALUE),
    YEAR(DATE_VALUE)
FROM (
    SELECT DATEADD(
        DAY,
        SEQ4(),
        '2026-01-01'::DATE
    ) AS DATE_VALUE
    FROM TABLE(GENERATOR(ROWCOUNT => 90))
);

