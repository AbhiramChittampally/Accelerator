-- Drill-across admissions by hospital
WITH ADMISSIONS AS (
    SELECT
        HOSPITAL_KEY,
        SUM(ADMISSION_COUNT) AS TOTAL_ADMISSIONS
    FROM FACT_ADMISSION
    GROUP BY HOSPITAL_KEY
),
BILLING AS (
    SELECT
        HOSPITAL_KEY,
        SUM(NET_AMOUNT) AS TOTAL_REVENUE
    FROM FACT_BILLING
    GROUP BY HOSPITAL_KEY
)
SELECT
    H.HOSPITAL_NAME,
    A.TOTAL_ADMISSIONS,
    B.TOTAL_REVENUE
FROM DIM_HOSPITAL H
LEFT JOIN ADMISSIONS A
    ON H.HOSPITAL_KEY = A.HOSPITAL_KEY
LEFT JOIN BILLING B
    ON H.HOSPITAL_KEY = B.HOSPITAL_KEY
ORDER BY H.HOSPITAL_NAME;

