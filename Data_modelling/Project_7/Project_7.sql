-- Admission count by hospital
SELECT
    H.HOSPITAL_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_HOSPITAL H
    ON F.HOSPITAL_KEY = H.HOSPITAL_KEY
GROUP BY H.HOSPITAL_NAME
ORDER BY TOTAL_ADMISSIONS DESC;

-- Admission count by department
SELECT
    D.DEPARTMENT_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_DEPARTMENT D
    ON F.DEPARTMENT_KEY = D.DEPARTMENT_KEY
GROUP BY D.DEPARTMENT_NAME
ORDER BY TOTAL_ADMISSIONS DESC;

-- Admission count by doctor
SELECT
    D.DOCTOR_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_DOCTOR D
    ON F.DOCTOR_KEY = D.DOCTOR_KEY
GROUP BY D.DOCTOR_NAME
ORDER BY TOTAL_ADMISSIONS DESC;

-- Monthly admissions
SELECT
    D.YEAR,
    D.MONTH,
    D.MONTH_NAME,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_DATE D
    ON F.DATE_KEY = D.DATE_KEY
GROUP BY
    D.YEAR,
    D.MONTH,
    D.MONTH_NAME
ORDER BY
    D.YEAR,
    D.MONTH;

-- Average length of stay
SELECT
    AVG(LENGTH_OF_STAY) AS AVERAGE_LENGTH_OF_STAY
FROM FACT_ADMISSION;

-- Total length of stay by hospital
SELECT
    H.HOSPITAL_NAME,
    SUM(F.LENGTH_OF_STAY) AS TOTAL_LENGTH_OF_STAY
FROM FACT_ADMISSION F
JOIN DIM_HOSPITAL H
    ON F.HOSPITAL_KEY = H.HOSPITAL_KEY
GROUP BY H.HOSPITAL_NAME
ORDER BY TOTAL_LENGTH_OF_STAY DESC;

