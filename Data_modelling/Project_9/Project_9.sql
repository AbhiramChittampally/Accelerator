-- Task 11: Create SCD Type 2 table
CREATE OR REPLACE TABLE DIM_CUSTOMER_TYPE2 (
    CUSTOMER_KEY INTEGER AUTOINCREMENT,
    CUSTOMER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30),
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE,
    IS_CURRENT BOOLEAN
);


-- Task 12: Load initial Type 2 records
-- Load directly from the original initial CSV
-- Do not load from the already-updated Type 1 table
INSERT INTO DIM_CUSTOMER_TYPE2 (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    '2026-01-01',
    '9999-12-31',
    TRUE
FROM (
    SELECT
        $1::INTEGER AS CUSTOMER_ID,
        $2::VARCHAR AS CUSTOMER_NAME,
        $3::VARCHAR AS CITY,
        $4::VARCHAR AS STATE,
        $5::VARCHAR AS MEMBERSHIP,
        $6::VARCHAR AS SEGMENT
    FROM @RETAIL9_STAGE/customers_initial.csv
    (FILE_FORMAT => 'RETAIL9_CSV_FORMAT')
);


-- Verify initial Type 2 records
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
FROM DIM_CUSTOMER_TYPE2
ORDER BY CUSTOMER_ID;


-- Task 10/11/12: Apply Type 2 changes
-- Step 1: Expire old records
UPDATE DIM_CUSTOMER_TYPE2 d
SET
    EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE),
    IS_CURRENT = FALSE
FROM CUSTOMER_UPDATES u
WHERE
    d.CUSTOMER_ID = u.CUSTOMER_ID
    AND d.IS_CURRENT = TRUE
    AND (
           d.CITY <> u.CITY
        OR d.STATE <> u.STATE
        OR d.MEMBERSHIP <> u.MEMBERSHIP
        OR d.SEGMENT <> u.SEGMENT
    );


-- Step 2: Insert new Type 2 records
INSERT INTO DIM_CUSTOMER_TYPE2 (
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    u.CUSTOMER_ID,
    u.CUSTOMER_NAME,
    u.CITY,
    u.STATE,
    u.MEMBERSHIP,
    u.SEGMENT,
    u.EFFECTIVE_DATE,
    '9999-12-31',
    TRUE
FROM CUSTOMER_UPDATES u;


-- Task 14: Display complete Type 2 history
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
