-- Task 1: Create database and schema
CREATE DATABASE IF NOT EXISTS RETAIL9_DB;

CREATE SCHEMA IF NOT EXISTS RETAIL9_DB.SALES_SCHEMA;

-- Select warehouse
CREATE WAREHOUSE IF NOT EXISTS RETAIL9_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

USE WAREHOUSE RETAIL9_WH;
USE DATABASE RETAIL9_DB;
USE SCHEMA SALES_SCHEMA;


-- Task 2: Create SCD Type 1 table
CREATE OR REPLACE TABLE DIM_CUSTOMER_TYPE1 (
    CUSTOMER_KEY INTEGER AUTOINCREMENT,
    CUSTOMER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30)
);


-- Create CSV file format
CREATE FILE FORMAT IF NOT EXISTS RETAIL9_CSV_FORMAT
TYPE = 'CSV'
SKIP_HEADER = 1
FIELD_DELIMITER = ','
FIELD_OPTIONALLY_ENCLOSED_BY = '"';


-- Create internal stage
CREATE STAGE IF NOT EXISTS RETAIL9_STAGE
FILE_FORMAT = RETAIL9_CSV_FORMAT;


-- Check uploaded files
LIST @RETAIL9_STAGE;


-- Task 3: Load initial Type 1 data
COPY INTO DIM_CUSTOMER_TYPE1
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT
)
FROM @RETAIL9_STAGE/customers_initial.csv
FILE_FORMAT = RETAIL9_CSV_FORMAT;


-- Verify initial Type 1 records
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    STATE,
    MEMBERSHIP,
    SEGMENT
FROM DIM_CUSTOMER_TYPE1
ORDER BY CUSTOMER_ID;


-- Verify initial customer count
SELECT COUNT(*) AS TOTAL_CUSTOMERS
FROM DIM_CUSTOMER_TYPE1;


-- Create staging table for customer updates
CREATE OR REPLACE TABLE CUSTOMER_UPDATES (
    CUSTOMER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30),
    EFFECTIVE_DATE DATE
);


-- Task 5: Load customer updates
COPY INTO CUSTOMER_UPDATES
FROM @RETAIL9_STAGE/customer_updates.csv
FILE_FORMAT = RETAIL9_CSV_FORMAT;


-- Verify customer updates
SELECT *
FROM CUSTOMER_UPDATES
ORDER BY CUSTOMER_ID;


-- Verify update record count
SELECT COUNT(*) AS RECORDS_RECEIVED
FROM CUSTOMER_UPDATES;


-- Task 6: Identify changed customers
SELECT
    d.CUSTOMER_ID,
    d.CITY AS OLD_CITY,
    u.CITY AS NEW_CITY,
    d.MEMBERSHIP AS OLD_MEMBERSHIP,
    u.MEMBERSHIP AS NEW_MEMBERSHIP
FROM DIM_CUSTOMER_TYPE1 d
JOIN CUSTOMER_UPDATES u
    ON d.CUSTOMER_ID = u.CUSTOMER_ID
WHERE
       d.CITY <> u.CITY
    OR d.STATE <> u.STATE
    OR d.MEMBERSHIP <> u.MEMBERSHIP
    OR d.SEGMENT <> u.SEGMENT
ORDER BY d.CUSTOMER_ID;


-- Task 7: Identify attribute changes
SELECT
    d.CUSTOMER_ID,
    'CITY' AS ATTRIBUTE,
    d.CITY AS OLD_VALUE,
    u.CITY AS NEW_VALUE
FROM DIM_CUSTOMER_TYPE1 d
JOIN CUSTOMER_UPDATES u
    ON d.CUSTOMER_ID = u.CUSTOMER_ID
WHERE d.CITY <> u.CITY

UNION ALL

SELECT
    d.CUSTOMER_ID,
    'STATE' AS ATTRIBUTE,
    d.STATE AS OLD_VALUE,
    u.STATE AS NEW_VALUE
FROM DIM_CUSTOMER_TYPE1 d
JOIN CUSTOMER_UPDATES u
    ON d.CUSTOMER_ID = u.CUSTOMER_ID
WHERE d.STATE <> u.STATE

UNION ALL

SELECT
    d.CUSTOMER_ID,
    'MEMBERSHIP' AS ATTRIBUTE,
    d.MEMBERSHIP AS OLD_VALUE,
    u.MEMBERSHIP AS NEW_VALUE
FROM DIM_CUSTOMER_TYPE1 d
JOIN CUSTOMER_UPDATES u
    ON d.CUSTOMER_ID = u.CUSTOMER_ID
WHERE d.MEMBERSHIP <> u.MEMBERSHIP

UNION ALL

SELECT
    d.CUSTOMER_ID,
    'SEGMENT' AS ATTRIBUTE,
    d.SEGMENT AS OLD_VALUE,
    u.SEGMENT AS NEW_VALUE
FROM DIM_CUSTOMER_TYPE1 d
JOIN CUSTOMER_UPDATES u
    ON d.CUSTOMER_ID = u.CUSTOMER_ID
WHERE d.SEGMENT <> u.SEGMENT

ORDER BY CUSTOMER_ID, ATTRIBUTE;


-- Task 8: Demonstrate SCD Type 1 problem
