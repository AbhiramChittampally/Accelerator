-- Task 26: Identify HIGH-RISK accounts that were NEVER audited in 2026

SELECT
    F.SENDER_ACC AS ACCOUNT_ID,
    COUNT(*) AS HIGH_RISK_TXN_COUNT,
    'NEVER_AUDITED' AS COMPLIANCE_STATUS
FROM P19C_FACT_WIRE_TRANSFERS F
JOIN P19C_DIM_WIRE_ATTRIBUTES D
    ON F.ATTRIBUTE_SK = D.ATTRIBUTE_SK
LEFT JOIN (
    SELECT DISTINCT
        ACCOUNT_ID
    FROM P19C_FACTLESS_COMPLIANCE_AUDIT_COVERAGE
    WHERE AUDIT_YEAR = 2026
) A
    ON F.SENDER_ACC = A.ACCOUNT_ID
WHERE D.RISK_FLAG = 'HIGH'
  AND A.ACCOUNT_ID IS NULL
GROUP BY F.SENDER_ACC
ORDER BY F.SENDER_ACC;


