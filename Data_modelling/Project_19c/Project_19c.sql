-- Task 20: Create Accumulating Credit Approval Snapshot

CREATE OR REPLACE TABLE P19C_FACT_CREDIT_APPROVAL_LIFECYCLE (
    APP_ID VARCHAR(20),
    SUBMISSION_DATE DATE,
    UNDERWRITE_DATE DATE,
    RISK_APPROVAL_DATE DATE,
    DISBURSEMENT_DATE DATE,
    UNDERWRITE_DAYS INTEGER,
    RISK_APPROVAL_DAYS INTEGER,
    DISBURSEMENT_DAYS INTEGER,
    TOTAL_CYCLE_DAYS INTEGER
);


-- Task 21: Populate Accumulating Snapshot

INSERT INTO P19C_FACT_CREDIT_APPROVAL_LIFECYCLE (
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,
    UNDERWRITE_DAYS,
    RISK_APPROVAL_DAYS,
    DISBURSEMENT_DAYS,
    TOTAL_CYCLE_DAYS
)
SELECT
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,

    CASE
        WHEN UNDERWRITE_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            SUBMISSION_DATE,
            UNDERWRITE_DATE
        )
    END AS UNDERWRITE_DAYS,

    CASE
        WHEN RISK_APPROVAL_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            UNDERWRITE_DATE,
            RISK_APPROVAL_DATE
        )
    END AS RISK_APPROVAL_DAYS,

    CASE
        WHEN DISBURSEMENT_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            RISK_APPROVAL_DATE,
            DISBURSEMENT_DATE
        )
    END AS DISBURSEMENT_DAYS,

    CASE
        WHEN DISBURSEMENT_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            SUBMISSION_DATE,
            DISBURSEMENT_DATE
        )
    END AS TOTAL_CYCLE_DAYS

FROM P19C_RAW_CREDIT_LIFECYCLES;


