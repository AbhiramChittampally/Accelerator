    COUNT(F.TXN_ID) AS TOTAL_TXNS,
    SUM(F.FEE) AS TOTAL_FEES,
    SUM(F.BASE_AMOUNT_USD) AS TOTAL_VOLUME_USD
FROM P19C_FACT_WIRE_TRANSFERS F
