-- Task 13: Build Junk Dimension

CREATE OR REPLACE TABLE P19C_DIM_WIRE_ATTRIBUTES (
    ATTRIBUTE_SK INTEGER,
    AUTH_METHOD VARCHAR(30),
    RISK_FLAG VARCHAR(20),
    TRANSFER_TYPE VARCHAR(30)
);


-- Task 14: Populate Junk Dimension

INSERT INTO P19C_DIM_WIRE_ATTRIBUTES (
    ATTRIBUTE_SK,
    AUTH_METHOD,
    RISK_FLAG,
    TRANSFER_TYPE
)
SELECT
    ROW_NUMBER() OVER (ORDER BY FIRST_TXN_ID) AS ATTRIBUTE_SK,
    AUTH_METHOD,
    RISK_FLAG,
    TRANSFER_TYPE
FROM (
    SELECT
        AUTH_METHOD,
        RISK_FLAG,
        TRANSFER_TYPE,
        MIN(TXN_ID) AS FIRST_TXN_ID
    FROM P19C_RAW_WIRE_TRANSFERS
    GROUP BY
        AUTH_METHOD,
        RISK_FLAG,
        TRANSFER_TYPE
);


-- Verify Junk Dimension

SELECT
    ATTRIBUTE_SK,
    AUTH_METHOD,
    RISK_FLAG,
    TRANSFER_TYPE
FROM P19C_DIM_WIRE_ATTRIBUTES
ORDER BY ATTRIBUTE_SK;


-- Task 15: Create Transaction Fact Table

CREATE OR REPLACE TABLE P19C_FACT_WIRE_TRANSFERS (
    TXN_ID VARCHAR(20),
    TXN_DATE DATE,
    SENDER_ACC VARCHAR(20),
    RECEIVER_ACC VARCHAR(20),
    ATTRIBUTE_SK INTEGER,
    AMOUNT NUMBER(18,2),
    FEE NUMBER(18,2),
    CURRENCY_RATE NUMBER(10,4),
    BASE_AMOUNT_USD NUMBER(18,2),
    NET_TRANSFER_VAL NUMBER(18,2)
);


-- Task 16: Populate Transaction Fact Table

INSERT INTO P19C_FACT_WIRE_TRANSFERS (
    TXN_ID,
    TXN_DATE,
    SENDER_ACC,
    RECEIVER_ACC,
    ATTRIBUTE_SK,
    AMOUNT,
    FEE,
    CURRENCY_RATE,
    BASE_AMOUNT_USD,
    NET_TRANSFER_VAL
)
SELECT
    W.TXN_ID,
    W.TXN_DATE,
    W.SENDER_ACC,
    W.RECEIVER_ACC,
    D.ATTRIBUTE_SK,
    W.AMOUNT,
    W.FEE,
    W.CURRENCY_RATE,

    W.AMOUNT * W.CURRENCY_RATE AS BASE_AMOUNT_USD,

    (W.AMOUNT * W.CURRENCY_RATE) - W.FEE AS NET_TRANSFER_VAL

FROM P19C_RAW_WIRE_TRANSFERS W
JOIN P19C_DIM_WIRE_ATTRIBUTES D
    ON W.AUTH_METHOD = D.AUTH_METHOD
    AND W.RISK_FLAG = D.RISK_FLAG
    AND W.TRANSFER_TYPE = D.TRANSFER_TYPE;


