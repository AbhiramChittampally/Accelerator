-- Point-in-time POS analytics

SELECT
    F.TRANSACTION_ID,
    F.TRANSACTION_DATE,
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY AS CURRENT_CITY,
    C.HISTORICAL_MEMBERSHIP AS MEMBERSHIP_AT_PURCHASE,
    C.SEGMENT AS SEGMENT_AT_PURCHASE,
    S.STORE_NAME,
    P.PRODUCT_NAME,
    F.TOTAL_AMOUNT
FROM RETAIL12_FACT_SALES F
JOIN RETAIL12_DIM_CUSTOMER_HYBRID C
    ON F.CUSTOMER_KEY = C.CUSTOMER_KEY
JOIN RETAIL12_DIM_STORE S
    ON F.STORE_KEY = S.STORE_KEY
JOIN RETAIL12_DIM_PRODUCT P
    ON F.PRODUCT_KEY = P.PRODUCT_KEY
WHERE C.CUSTOMER_ID = 101
ORDER BY F.TRANSACTION_DATE;


