-- Create Sales fact table

CREATE OR REPLACE TABLE RETAIL12_FACT_SALES (
    SALES_KEY NUMBER AUTOINCREMENT PRIMARY KEY,
    TRANSACTION_ID VARCHAR(50),
    TRANSACTION_DATE DATE,
    CUSTOMER_KEY NUMBER,
    STORE_KEY NUMBER,
    PRODUCT_KEY NUMBER,
    QUANTITY NUMBER,
    UNIT_PRICE NUMBER(10,2),
    TOTAL_AMOUNT NUMBER(12,2),
    FOREIGN KEY (CUSTOMER_KEY)
        REFERENCES RETAIL12_DIM_CUSTOMER_HYBRID(CUSTOMER_KEY),
    FOREIGN KEY (STORE_KEY)
        REFERENCES RETAIL12_DIM_STORE(STORE_KEY),
    FOREIGN KEY (PRODUCT_KEY)
        REFERENCES RETAIL12_DIM_PRODUCT(PRODUCT_KEY)
);


