-- Task 11: Build Junk Dimension

CREATE OR REPLACE TABLE P19A_DIM_ORDER_INDICATORS (
    INDICATOR_SK INTEGER,
    PAYMENT_METHOD VARCHAR(30),
    SHIPPING_OPTION VARCHAR(30),
    GIFT_WRAP_FLAG VARCHAR(1)
);


-- Task 12: Populate Junk Dimension

INSERT INTO P19A_DIM_ORDER_INDICATORS (
    INDICATOR_SK,
    PAYMENT_METHOD,
    SHIPPING_OPTION,
    GIFT_WRAP_FLAG
)
SELECT
    ROW_NUMBER() OVER (ORDER BY FIRST_ORDER_ID) AS INDICATOR_SK,
    PAYMENT_METHOD,
    SHIPPING_OPTION,
    GIFT_WRAP_FLAG
FROM (
    SELECT
        PAYMENT_METHOD,
        SHIPPING_OPTION,
        GIFT_WRAP_FLAG,
        MIN(ORDER_ID) AS FIRST_ORDER_ID
    FROM P19A_RAW_ORDERS
    GROUP BY
        PAYMENT_METHOD,
        SHIPPING_OPTION,
        GIFT_WRAP_FLAG
);


-- Verify Junk Dimension

SELECT
    INDICATOR_SK,
    PAYMENT_METHOD,
    SHIPPING_OPTION,
    GIFT_WRAP_FLAG
FROM P19A_DIM_ORDER_INDICATORS
ORDER BY INDICATOR_SK;


-- Task 13: Create Transaction Fact Table

CREATE OR REPLACE TABLE P19A_FACT_SALES_TRANSACTIONS (
    ORDER_ID VARCHAR(20),
    ORDER_DATE DATE,
    USER_ID VARCHAR(20),
    STORE_ID VARCHAR(20),
    INDICATOR_SK INTEGER,
    AMOUNT NUMBER(12,2),
    TAX NUMBER(12,2)
);


-- Task 14: Populate Transaction Fact Table

INSERT INTO P19A_FACT_SALES_TRANSACTIONS (
    ORDER_ID,
    ORDER_DATE,
    USER_ID,
    STORE_ID,
    INDICATOR_SK,
    AMOUNT,
    TAX
)
SELECT
    O.ORDER_ID,
    O.ORDER_DATE,
    O.USER_ID,
    O.STORE_ID,
    D.INDICATOR_SK,
    O.AMOUNT,
    O.TAX
FROM P19A_RAW_ORDERS O
JOIN P19A_DIM_ORDER_INDICATORS D
    ON O.PAYMENT_METHOD = D.PAYMENT_METHOD
    AND O.SHIPPING_OPTION = D.SHIPPING_OPTION
    AND O.GIFT_WRAP_FLAG = D.GIFT_WRAP_FLAG;


-- Verify Transaction Fact Table

SELECT
    ORDER_ID,
    INDICATOR_SK,
    AMOUNT
FROM P19A_FACT_SALES_TRANSACTIONS
ORDER BY ORDER_ID;


-- Task 15: Create Periodic Snapshot Fact Table

CREATE OR REPLACE TABLE P19A_FACT_INVENTORY_SNAPSHOT (
    SNAPSHOT_DATE DATE,
    STORE_ID VARCHAR(20),
    TOTAL_UNITS_HELD NUMBER,
    TOTAL_INVENTORY_VAL NUMBER(14,2)
);


-- Task 16: Populate Periodic Snapshot Fact Table

INSERT INTO P19A_FACT_INVENTORY_SNAPSHOT (
    SNAPSHOT_DATE,
    STORE_ID,
    TOTAL_UNITS_HELD,
    TOTAL_INVENTORY_VAL
)
SELECT
    SNAPSHOT_DATE,
    STORE_ID,
    SUM(QTY_ON_HAND) AS TOTAL_UNITS_HELD,
    SUM(QTY_ON_HAND * UNIT_COST) AS TOTAL_INVENTORY_VAL
FROM P19A_RAW_INVENTORY
GROUP BY
    SNAPSHOT_DATE,
    STORE_ID;


-- Verify Periodic Snapshot Fact Table

SELECT
    SNAPSHOT_DATE,
    STORE_ID,
    TOTAL_UNITS_HELD,
    TOTAL_INVENTORY_VAL
FROM P19A_FACT_INVENTORY_SNAPSHOT
ORDER BY SNAPSHOT_DATE, STORE_ID;


-- Task 17: Create Accumulating Snapshot Fact Table

CREATE OR REPLACE TABLE P19A_FACT_ORDER_FULFILLMENT (
    ORDER_ID VARCHAR(20),
    ORDER_DATE DATE,
    PICK_DATE DATE,
    SHIP_DATE DATE,
    DELIVERY_DATE DATE,
    PICK_LAG_DAYS INTEGER,
    SHIP_LAG_DAYS INTEGER,
    DELIVERY_LAG_DAYS INTEGER,
    TOTAL_FULFILLMENT_DAYS INTEGER
);


-- Task 18: Populate Accumulating Snapshot Fact Table

INSERT INTO P19A_FACT_ORDER_FULFILLMENT (
    ORDER_ID,
    ORDER_DATE,
    PICK_DATE,
    SHIP_DATE,
    DELIVERY_DATE,
    PICK_LAG_DAYS,
    SHIP_LAG_DAYS,
    DELIVERY_LAG_DAYS,
    TOTAL_FULFILLMENT_DAYS
)
SELECT
    ORDER_ID,
    ORDER_DATE,
    PICK_DATE,
    SHIP_DATE,
    DELIVERY_DATE,

    DATEDIFF(
        'day',
        ORDER_DATE,
        PICK_DATE
    ) AS PICK_LAG_DAYS,

    CASE
        WHEN SHIP_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            PICK_DATE,
            SHIP_DATE
        )
    END AS SHIP_LAG_DAYS,

    CASE
        WHEN DELIVERY_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            SHIP_DATE,
            DELIVERY_DATE
        )
    END AS DELIVERY_LAG_DAYS,

    CASE
        WHEN DELIVERY_DATE IS NOT NULL
        THEN DATEDIFF(
            'day',
            ORDER_DATE,
            DELIVERY_DATE
        )
    END AS TOTAL_FULFILLMENT_DAYS

FROM P19A_RAW_FULFILLMENT;


-- Verify completed fulfillment records

SELECT
    ORDER_ID,
    PICK_LAG_DAYS,
    SHIP_LAG_DAYS,
    DELIVERY_LAG_DAYS,
    TOTAL_FULFILLMENT_DAYS
FROM P19A_FACT_ORDER_FULFILLMENT
WHERE DELIVERY_LAG_DAYS IS NOT NULL
ORDER BY ORDER_ID;


-- Task 19: Audit incomplete order lifecycles

SELECT
    ORDER_ID,
    ORDER_DATE,
    CASE
        WHEN DELIVERY_DATE IS NOT NULL
            THEN 'DELIVERED'

        WHEN SHIP_DATE IS NOT NULL
            THEN 'SHIPPED_NOT_DELIVERED'

        WHEN PICK_DATE IS NOT NULL
            THEN 'PICKED_NOT_SHIPPED'

        ELSE 'NOT_PICKED'
    END AS CURRENT_STATUS
FROM P19A_FACT_ORDER_FULFILLMENT
WHERE DELIVERY_DATE IS NULL
ORDER BY ORDER_ID;


-- Task 20: Aggregate revenue by Junk Dimension indicators

SELECT
    D.PAYMENT_METHOD,
    COUNT(F.ORDER_ID) AS TOTAL_ORDERS,
    SUM(F.AMOUNT) AS TOTAL_REVENUE
FROM P19A_FACT_SALES_TRANSACTIONS F
JOIN P19A_DIM_ORDER_INDICATORS D
    ON F.INDICATOR_SK = D.INDICATOR_SK
GROUP BY D.PAYMENT_METHOD
ORDER BY D.PAYMENT_METHOD;


