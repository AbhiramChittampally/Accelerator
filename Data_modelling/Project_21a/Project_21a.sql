SELECT
    'POS_SALES' AS DATASET,
    COUNT(*) AS LOADED_ROWS
FROM RAW_SALES_STG

UNION ALL

SELECT
    'INVENTORY',
    COUNT(*)
FROM RAW_INVENTORY_STG;

SELECT
    'Sales Analysis' AS BUSINESS_PROCESS,

    CASE
        WHEN COUNT(DISTINCT S.STORE_ID) =
             COUNT(DISTINCT DS.STORE_ID)
        THEN 'YES'
        ELSE 'NO'
    END AS CONFORMED_STORE,

    CASE
        WHEN COUNT(DISTINCT S.PRODUCT_ID) =
             COUNT(DISTINCT DP.PRODUCT_ID)
        THEN 'YES'
        ELSE 'NO'
    END AS CONFORMED_PRODUCT

FROM RAW_SALES_STG S
JOIN DIM_STORE DS
    ON S.STORE_ID = DS.STORE_ID
JOIN DIM_PRODUCT DP
    ON S.PRODUCT_ID = DP.PRODUCT_ID

UNION ALL

SELECT
    'Inventory Snapshot',

    CASE
        WHEN COUNT(DISTINCT I.STORE_ID) =
             COUNT(DISTINCT DS.STORE_ID)
        THEN 'YES'
        ELSE 'NO'
    END,

    CASE
        WHEN COUNT(DISTINCT I.PRODUCT_ID) =
             COUNT(DISTINCT DP.PRODUCT_ID)
        THEN 'YES'
        ELSE 'NO'
    END

FROM RAW_INVENTORY_STG I
JOIN DIM_STORE DS
    ON I.STORE_ID = DS.STORE_ID
JOIN DIM_PRODUCT DP
    ON I.PRODUCT_ID = DP.PRODUCT_ID;

CREATE OR REPLACE VIEW VIEW_SALES_MART AS
SELECT
    SALE_ID,
    STORE_ID,
    PRODUCT_ID,
    AMOUNT
FROM RAW_SALES_STG;

SELECT *
FROM VIEW_SALES_MART
ORDER BY SALE_ID;

CREATE OR REPLACE VIEW VIEW_INVENTORY_MART AS
SELECT
    SNAPSHOT_ID,
    STORE_ID,
    PRODUCT_ID,
    ON_HAND_QTY
FROM RAW_INVENTORY_STG;

SELECT *
FROM VIEW_INVENTORY_MART
ORDER BY SNAPSHOT_ID;

MERGE INTO DIM_STORE T
USING (
    SELECT
        'STR-10' AS STORE_ID,
        'Downtown Store Flagship' AS STORE_NAME,
        'East' AS REGION
) S
ON T.STORE_ID = S.STORE_ID

WHEN MATCHED THEN
    UPDATE SET
        T.STORE_NAME = S.STORE_NAME,
        T.REGION = S.REGION

WHEN NOT MATCHED THEN
    INSERT (
        STORE_ID,
        STORE_NAME,
        REGION
    )
    VALUES (
        S.STORE_ID,
        S.STORE_NAME,
        S.REGION
    );

SELECT
    "number of rows inserted" AS ROWS_INSERTED,
    "number of rows updated" AS ROWS_UPDATED
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

SELECT
    'FACT_DIM_FK_MATCH' AS INTEGRITY_CHECK,

    (
        SELECT COUNT(*)
        FROM RAW_SALES_STG S
        LEFT JOIN DIM_STORE DS
            ON S.STORE_ID = DS.STORE_ID
        LEFT JOIN DIM_PRODUCT DP
            ON S.PRODUCT_ID = DP.PRODUCT_ID
        WHERE DS.STORE_ID IS NULL
           OR DP.PRODUCT_ID IS NULL
    )
    +
    (
        SELECT COUNT(*)
        FROM RAW_INVENTORY_STG I
        LEFT JOIN DIM_STORE DS
            ON I.STORE_ID = DS.STORE_ID
        LEFT JOIN DIM_PRODUCT DP
            ON I.PRODUCT_ID = DP.PRODUCT_ID
        WHERE DS.STORE_ID IS NULL
           OR DP.PRODUCT_ID IS NULL
    ) AS FAILED_RECORDS;

