    CASE
        WHEN
            (
                SELECT CLUSTERING_KEY
                FROM P21A_RETAIL_DB.INFORMATION_SCHEMA.TABLES
                WHERE TABLE_SCHEMA = 'RETAIL_SCHEMA'
                  AND TABLE_NAME = 'DIM_STORE'
            ) IS NOT NULL
        AND
            (
                SELECT CLUSTERING_KEY
                FROM P21A_RETAIL_DB.INFORMATION_SCHEMA.TABLES
                WHERE TABLE_SCHEMA = 'RETAIL_SCHEMA'
                  AND TABLE_NAME = 'DIM_PRODUCT'
            ) IS NOT NULL
        THEN 'COMPLETED'
        ELSE 'NOT COMPLETED'
    END AS STATUS;