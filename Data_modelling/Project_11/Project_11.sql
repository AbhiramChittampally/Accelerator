-- Task 7: Display active customer report

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    SEGMENT
FROM DIM_CUSTOMER_HYBRID
WHERE IS_CURRENT = TRUE
ORDER BY CUSTOMER_ID;


-- Task 8: Point-in-time historical query

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE
FROM DIM_CUSTOMER_HYBRID
WHERE CUSTOMER_ID = 101
  AND '2026-03-15'::DATE
      BETWEEN EFFECTIVE_DATE AND EXPIRY_DATE;


-- Task 9: Metric validation

SELECT
    COUNT(*) AS TOTAL_RECORD_COUNT,
    COUNT_IF(IS_CURRENT = TRUE) AS CURRENT_RECORD_COUNT,
    COUNT_IF(IS_CURRENT = FALSE) AS HISTORICAL_RECORD_COUNT
FROM DIM_CUSTOMER_HYBRID;