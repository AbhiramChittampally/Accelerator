-- Task 1: Create database and schema

CREATE WAREHOUSE IF NOT EXISTS RETAIL11_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE DATABASE IF NOT EXISTS RETAIL11_DB;

CREATE SCHEMA IF NOT EXISTS RETAIL11_DB.SALES_SCHEMA;

USE WAREHOUSE RETAIL11_WH;

USE DATABASE RETAIL11_DB;

USE SCHEMA SALES_SCHEMA;

SELECT
    CURRENT_WAREHOUSE(),
    CURRENT_DATABASE(),
    CURRENT_SCHEMA();


-- Task 2: Create hybrid dimension table

CREATE OR REPLACE TABLE DIM_CUSTOMER_HYBRID (
    CUSTOMER_KEY INTEGER AUTOINCREMENT,
    CUSTOMER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    PREVIOUS_CITY VARCHAR(50),
    STATE VARCHAR(50),
    CURRENT_MEMBERSHIP VARCHAR(30),
    PREVIOUS_MEMBERSHIP VARCHAR(30),
    HISTORICAL_MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30),
    EFFECTIVE_DATE DATE,
    EXPIRY_DATE DATE,
    IS_CURRENT BOOLEAN
);


-- Task 3: Create CSV file format

CREATE OR REPLACE FILE FORMAT RETAIL11_CSV_FORMAT
TYPE = 'CSV'
SKIP_HEADER = 1
FIELD_DELIMITER = ','
FIELD_OPTIONALLY_ENCLOSED_BY = '"';


-- Task 3: Create stage

CREATE OR REPLACE STAGE RETAIL11_STAGE
FILE_FORMAT = RETAIL11_CSV_FORMAT;


-- Task 3: Load initial customer data

COPY INTO DIM_CUSTOMER_HYBRID
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
FROM (
    SELECT
        $1::INTEGER,
        $2::VARCHAR,
        $3::VARCHAR,
        NULL,
        $4::VARCHAR,
        $5::VARCHAR,
        NULL,
        $5::VARCHAR,
        $6::VARCHAR,
        '2026-01-01'::DATE,
        '9999-12-31'::DATE,
        TRUE
    FROM @RETAIL11_STAGE/customers_initial_project11.csv
)
FILE_FORMAT = RETAIL11_CSV_FORMAT;


-- Task 3: Validate initial records

SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT_IF(IS_CURRENT = TRUE) AS CURRENT_RECORDS
FROM DIM_CUSTOMER_HYBRID;


-- Task 4: Display initial dimension

SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
FROM DIM_CUSTOMER_HYBRID
ORDER BY CUSTOMER_ID;


-- Task 5: Create update table

CREATE OR REPLACE TABLE CUSTOMER_UPDATES (
    CUSTOMER_ID INTEGER,
    CUSTOMER_NAME VARCHAR(100),
    CITY VARCHAR(50),
    STATE VARCHAR(50),
    MEMBERSHIP VARCHAR(30),
    SEGMENT VARCHAR(30),
    EFFECTIVE_DATE DATE
);


-- Task 5: Load customer updates

COPY INTO CUSTOMER_UPDATES
FROM @RETAIL11_STAGE/customer_updates_project11.csv
FILE_FORMAT = RETAIL11_CSV_FORMAT;


-- Task 5: Expire Customer 101

UPDATE DIM_CUSTOMER_HYBRID
SET
    EXPIRY_DATE = '2026-03-31',
    IS_CURRENT = FALSE
WHERE CUSTOMER_ID = 101
  AND IS_CURRENT = TRUE;


