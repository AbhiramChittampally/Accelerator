  AND IS_CURRENT = TRUE;


-- Task 5: Insert new active versions

INSERT INTO DIM_CUSTOMER_HYBRID
(
    CUSTOMER_ID,
    CUSTOMER_NAME,
    CITY,
    PREVIOUS_CITY,
    STATE,
    CURRENT_MEMBERSHIP,
    PREVIOUS_MEMBERSHIP,
    HISTORICAL_MEMBERSHIP,
    SEGMENT,
    EFFECTIVE_DATE,
    EXPIRY_DATE,
    IS_CURRENT
)
SELECT
    u.CUSTOMER_ID,
    u.CUSTOMER_NAME,
    u.CITY,
    CASE
        WHEN u.CUSTOMER_ID = 101 THEN 'Hyderabad'
        WHEN u.CUSTOMER_ID = 103 THEN 'Vijayawada'
        WHEN u.CUSTOMER_ID = 104 THEN NULL
    END,
    u.STATE,
    u.MEMBERSHIP,
    CASE
        WHEN u.CUSTOMER_ID IN (101, 103) THEN 'Silver'
        WHEN u.CUSTOMER_ID = 104 THEN 'Gold'
    END,
    u.MEMBERSHIP,
    u.SEGMENT,
    u.EFFECTIVE_DATE,
    '9999-12-31'::DATE,
    TRUE
FROM CUSTOMER_UPDATES u;


